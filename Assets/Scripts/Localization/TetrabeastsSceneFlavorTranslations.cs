    static readonly Dictionary<string, Dictionary<string, string>> TextByLanguage = BuildTextByLanguage();

    public static bool TryGetText(string languageCode, string englishText, out string localizedText)
    {
        localizedText = null;

        if (string.IsNullOrWhiteSpace(englishText))
            return false;

        string code = NormalizeCode(languageCode);
        return TextByLanguage.TryGetValue(code, out var languageTable)
            && languageTable.TryGetValue(NormalizeLookupKey(englishText), out localizedText);
    }

    public static bool HasText(string englishText)
    {
        if (string.IsNullOrWhiteSpace(englishText))
            return false;

        string key = NormalizeLookupKey(englishText);
        foreach (var languageTable in TextByLanguage.Values)
        {
            if (languageTable.ContainsKey(key))
                return true;
        }

        return false;
    }

    static Dictionary<string, Dictionary<string, string>> BuildTextByLanguage()
    {
        return new Dictionary<string, Dictionary<string, string>>(StringComparer.OrdinalIgnoreCase)
        {
            ["es"] = CreateTable(SpanishText),
            ["pt-br"] = CreateTable(PortugueseBrazilText),
            ["de"] = CreateTable(GermanText),
            ["fr"] = CreateTable(FrenchText),
            ["ru"] = CreateTable(RussianText),
            ["zh-cn"] = CreateTable(ChineseSimplifiedText)
        };
    }

    static Dictionary<string, string> CreateTable(string[] localizedText)
    {
        var table = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
        int count = Math.Min(EnglishText.Length, localizedText?.Length ?? 0);
        for (int i = 0; i < count; i++)
            Add(table, EnglishText[i], localizedText[i]);

        return table;
    }

    static void Add(Dictionary<string, string> text, string english, string localized)
    {
        string key = NormalizeLookupKey(english);
        if (!string.IsNullOrEmpty(key))
            text[key] = localized;
    }

    static string NormalizeCode(string code)
    {
        return string.IsNullOrWhiteSpace(code)
            ? string.Empty
            : code.Trim().Replace('_', '-').ToLowerInvariant();
    }

    static string NormalizeLookupKey(string value)
    {
        if (string.IsNullOrWhiteSpace(value))
            return string.Empty;

        var builder = new StringBuilder(value.Length);
        bool previousWhitespace = false;

        for (int i = 0; i < value.Length; i++)
        {
            char c = value[i];
            if (char.IsWhiteSpace(c))
            {
                if (!previousWhitespace)
                    builder.Append(' ');

                previousWhitespace = true;
                continue;
            }

            if ((c == '\'' || c == '"') && builder.Length == 0)
                continue;

            builder.Append(c);
            previousWhitespace = false;
        }

        return builder.ToString().Trim();
    }
